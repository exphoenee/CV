export const MAP_PADDING_X = Math.floor(MAP_GRID[0].length / 2);
export const MAP_PADDING_Y = Math.floor(MAP_GRID.length / 2);
export const MAP_OFFSET_COL = MAP_PADDING_X;
export const MAP_OFFSET_ROW = MAP_PADDING_Y;
export const MAP_WIDTH = MAP_GRID[0].length + MAP_PADDING_X * 2;
export const MAP_HEIGHT = MAP_GRID.length + MAP_PADDING_Y * 2;

// Build a full (padded) map grid used at runtime for collision and rendering.
// The original `MAP_GRID` above remains the canonical source map (30x20).
// The runtime `FULL_MAP_GRID` is padded on all sides by MAP_PADDING_* so the
// visual world is larger while keeping the source map intact.
export const FULL_MAP_GRID = (function buildFullGrid() {
  const full = [];
  for (let r = 0; r < MAP_HEIGHT; r++) {
    const row = new Array(MAP_WIDTH).fill("G");
    full.push(row);
  }

  for (let r = 0; r < MAP_GRID.length; r++) {
    for (let c = 0; c < MAP_GRID[0].length; c++) {
      const fr = r + MAP_OFFSET_ROW;
      const fc = c + MAP_OFFSET_COL;
      full[fr][fc] = MAP_GRID[r][c];
    }
  }
  return full;
})();
